#!/usr/bin/env bash
# Verify that "only typescript, no vite" works: gen -> tsc compile -> the compiled JS runs directly in a browser (import map)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$ROOT"
npm run build:lib >/dev/null
TGZ="$(npm pack --silent --pack-destination "$WORK" | tail -1)"

cd "$WORK"
npm init -y >/dev/null
npm pkg set type=module >/dev/null
npm i -D typescript@7.0.2 >/dev/null
npm i -D "./$TGZ" >/dev/null
test ! -e node_modules/vite || { echo "[no-bundler] vite must not be installed" >&2; exit 1; }
mkdir src

cat > tsconfig.json <<'CFG'
{ "compilerOptions": { "target": "ES2022", "module": "NodeNext", "moduleResolution": "NodeNext",
  "lib": ["ES2022", "DOM"], "strict": true, "rootDir": "src", "outDir": "out", "skipLibCheck": true } }
CFG
cat > src/hello.html <<'HTML'
<style scoped>:scope { display: block }</style>
<h1>Hi {{ name }}</h1>
<button type="button" data-on-click="add">go</button>
<ul><template data-each="rows"><li>{{ n }}<b data-if="hot">!</b></li></template></ul>
<div class="extra"><slot name="extra"></slot></div>
<x-kid data-ref="kid" data-on-pinged="onPing"></x-kid>
<p class="pings">{{ pings }}</p>
HTML
cat > src/kid.html <<'HTML'
<span class="kid">{{ label }}</span>
<button type="button" data-on-click="ping">ping</button>
HTML
cat > src/kid.ts <<'TS'
import { Component, define, event } from "nativele";
import tpl from "./kid.html.js";

export class Kid extends Component(tpl, {
  props: { label: "" },
  emits: { pinged: event() },
}) {
  ping(): void {
    this.emit("pinged");
  }
}
define("x-kid", Kid);
TS
cat > src/hello.ts <<'TS'
import { Component, define } from "nativele";
import tpl from "./hello.html.js";

interface Row { id: number; n: string; hot: boolean }

class Hello extends Component(tpl, {
  state: { name: "world", pings: 0, rows: [{ id: 1, n: "a", hot: false }] as Row[] },
}) {
  onPing(): void {
    this.set((s) => ({ pings: s.pings + 1 }));
  }
  add(): void {
    this.set((s) => ({ rows: [...s.rows, { id: 2, n: "b", hot: true }] }));
  }
  override render(v: { rows: Row[]; pings: number }, changed: ReadonlySet<string>): void {
    this.refs.kid.label = `k${v.pings}`; // the child's prop types come from the HTMLElementTagNameMap generated by nativele gen
    if (!changed.has("rows")) return;
    this.lists.rows.replace(v.rows, (r) => r.id, (r, { text, show }) => {
      text.n = r.n;
      show("hot", r.hot);
    });
  }
}
define("x-hello", Hello);
TS
cat > index.html <<'HTML'
<!doctype html>
<script type="importmap">{ "imports": { "nativele": "/node_modules/nativele/dist/index.mjs" } }</script>
<x-hello><span slot="extra">S</span></x-hello>
<script type="module" src="/out/hello.js"></script>
HTML

echo "[no-bundler] gen";  npx nativele gen
echo "[no-bundler] tsc";  npx tsc
test -s out/hello.js && test -s out/hello.html.js
echo "[no-bundler] the type check rejects wrong names"
bad() { # $1=description $2=code that must make tsc fail
  printf 'import tpl from "./hello.html.js";\nimport { Component, define } from "nativele";\n%s\n' "$2" > src/bad.ts
  if npx tsc --noEmit >/dev/null 2>&1; then echo "[no-bundler] expected tsc to fail but it passed: $1" >&2; exit 1; fi
  rm src/bad.ts
}
bad "wrong refs / text / show names" 'class X extends Component(tpl) { m() { this.refs.nope; this.text.nope = 1; this.show("nope", true); } } void X;'
bad "the HTML uses a name that state does not have" 'class X extends Component(tpl, { state: { zzz: 1 } }) {} void X;'
bad "missing method for data-on-click" 'class X extends Component(tpl, { state: { name: "", rows: [] as unknown[] } }) {} define("x-bad", X);'
bad "wrong type for a child component prop" 'class X extends Component(tpl, { state: { name: "", pings: 0, rows: [] as unknown[] } }) { add() {} onPing() {} render() { this.refs.kid.label = 1; } } define("x-bad", X);'
bad "wrong field type in set()" 'class X extends Component(tpl, { state: { name: "", rows: [] as unknown[] } }) { add() { this.set({ name: 1 }); } } void X;'
echo "[no-bundler] run in a browser"
node "$ROOT/scripts/serve-and-check.ts" "$WORK"
echo "[no-bundler] OK"
