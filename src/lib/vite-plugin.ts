import { existsSync, readFileSync, unlinkSync } from "node:fs";
import { relative, resolve, sep } from "node:path";
import { CodegenError, formatDiagnostics, generateDirs, generateFile, isFullPage, isSelected, listHtml, regenerateDefines } from "./codegen.ts";
import { defineDefs, isTs, Memo, Workspace } from "./components.ts";
import type { DefineDef } from "./components.ts";
import { lintProject, lintTemplate } from "./lint.ts";

export interface TsDomPluginOptions {
  /** Directories to scan for .html files and generate .html.ts into, relative to Vite's root. Default: ["src"] */
  dirs?: string[];
  /** Module name the generated files import the runtime from. Default: "@nativele/ts-dom" */
  runtime?: string;
  /** How text nodes keep their whitespace: "preserve" (default) or "collapse" (see `GenerateOptions`). */
  whitespace?: "preserve" | "collapse";
  /** Glob patterns (relative to each directory) of the templates to generate. Default: all. */
  include?: string[];
  /** Glob patterns (relative to each directory) of templates to leave out. */
  exclude?: string[];
  /** Show ARIA / accessibility warnings in the terminal during builds. true enables every check; an object can list rule ids to ignore. Default: off. */
  a11y?: boolean | { ignore?: string[] };
}

interface Logger {
  error(m: string): void;
  warn(m: string): void;
}

interface HotServer {
  config: { logger: Logger };
  moduleGraph: { getModulesByFile(f: string): Set<unknown> | undefined; invalidateModule(m: unknown): void };
  ws: { send(payload: { type: "full-reload" }): void };
}

const GENERATED_HEADER = "// Generated by ts-dom.";
// Vite keys its module graph by forward-slash paths, also on Windows.
const slashes = (file: string) => file.split(sep).join("/");
const read = (file: string) => (existsSync(file) ? readFileSync(file, "utf8") : null);

/**
 * Optional Vite plugin: generates `.html.ts` when the build starts and regenerates it while the dev server runs.
 * ts-dom does not depend on it: `ts-dom gen` (or `--watch`) together with tsc is enough.
 */
export function tsDom(opts: TsDomPluginOptions = {}) {
  const generate = { runtime: opts.runtime, whitespace: opts.whitespace, include: opts.include, exclude: opts.exclude };
  const a11y = opts.a11y === true ? {} : opts.a11y || null;
  let root = process.cwd();
  let dirs = (opts.dirs ?? ["src"]).map((d) => resolve(d));
  // The content of each generated module that the pages were last reloaded for. One write can reach the watcher as several events, and other dev servers watching the same folder write the same content again: an event whose content was already reloaded for is dropped.
  const shown = new Map<string, string>();
  const memo = new Memo();
  let ws = new Workspace(memo);
  const existing = () => dirs.filter((d) => existsSync(d));
  const defs = () => defineDefs(ws.index(existing()));
  // The define() calls as of the last generation, and the files with one or with the class it registers: a change to one of them, also one that removes the define(), regenerates what depends on the define() calls.
  let generatedDefs: DefineDef[] = [];
  let defineFiles = new Set<string>();
  const noteDefines = () => {
    generatedDefs = defs();
    defineFiles = new Set(generatedDefs.flatMap((d) => [resolve(d.file), resolve(d.classFile)]));
  };
  const isDefineFile = (file: string) => defineFiles.has(file);

  const dirOf = (file: string) => dirs.find((d) => file.startsWith(d + sep));
  const templates = () => existing().flatMap((d) => listHtml(d, ws).filter((f) => isSelected(d, f, generate)).map((f) => resolve(f)));

  const printed = new Map<string, string>();
  const warnA11y = (warn: (m: string) => void, saved?: string) => {
    if (!a11y) return;
    const p = lintProject(ws, existing(), process.cwd());
    for (const f of templates()) {
      const lines = lintTemplate(p, f, ["a11y"]).a11y.filter((d) => !a11y.ignore?.includes(d.rule)).map((d) => formatDiagnostics(f, [d]));
      if (saved === undefined || f === saved || printed.get(f) !== lines.join("\n")) for (const line of lines) warn(line);
      printed.set(f, lines.join("\n"));
    }
  };
  const recheck = (file: string, logger: Logger) => warnA11y((m) => logger.warn(m), file);

  /** Regenerate one template. Returns whether its generated module changed. */
  const regenerate = (file: string, logger: Logger): boolean => {
    const dir = dirOf(file);
    const html = ws.text(file);
    if (!dir || html === null || file.includes(`${sep}node_modules${sep}`) || isFullPage(html) || !isSelected(dir, file, generate)) return false;
    const out = `${file}.ts`;
    const before = read(out);
    try {
      generateFile(file, generate, defs(), dir, ws);
    } catch (e) {
      if (e instanceof CodegenError) logger.error(e.message);
      else throw e;
      return false;
    }
    recheck(file, logger);
    return read(out) !== before;
  };

  /** Regenerate after a define() call may have changed: the tag maps and the templates that use a tag whose definition changed. */
  const regenerateDefs = (logger: Logger) => {
    let written: string[] = [];
    try {
      written = regenerateDefines(existing(), generate, generatedDefs, ws);
    } catch (e) {
      if (e instanceof CodegenError) logger.error(e.message);
      else throw e;
    }
    noteDefines();
    for (const out of written) {
      const now = out.endsWith(".html.ts") ? read(out) : null;
      if (now !== null) shown.set(out, now);
    }
  };

  const removeGenerated = (file: string) => {
    const out = `${file}.ts`;
    if (dirOf(file) && read(out)?.startsWith(GENERATED_HEADER)) unlinkSync(out);
  };

  const reload = (server: HotServer, out: string): void => {
    const now = read(out);
    if (now === null || shown.get(out) === now) return;
    shown.set(out, now);
    const loaded = server.moduleGraph.getModulesByFile(slashes(out));
    if (!loaded?.size) return;
    for (const m of loaded) server.moduleGraph.invalidateModule(m);
    server.ws.send({ type: "full-reload" });
  };

  return {
    name: "ts-dom",
    enforce: "pre" as const,
    configResolved(config: { root: string }) {
      root = config.root;
      dirs = (opts.dirs ?? ["src"]).map((d) => resolve(config.root, d));
    },
    buildStart(this: { error(m: string): never; warn(m: string): void }) {
      ws = new Workspace(memo);
      for (const d of dirs) {
        if (!existsSync(d)) this.warn(`${relative(process.cwd(), d) || "."}:1:1 warning [dir-not-found] The folder ${d} given in tsDom({ dirs }) does not exist, so no templates in it are generated. Fix: dirs are resolved against Vite's root (${root}), not the working directory; give the folder relative to that root, or an absolute path.`);
      }
      try {
        generateDirs(existing(), generate, ws);
      } catch (e) {
        if (e instanceof CodegenError) this.error(e.message);
        throw e;
      }
      noteDefines();
      warnA11y((m) => this.warn(m));
    },
    configureServer(server: { watcher: { add(p: string | string[]): void; on(ev: string, fn: (f: string) => void): void }; config: { logger: Logger } }) {
      const logger = server.config.logger;
      server.watcher.add(dirs);
      server.watcher.on("add", (f) => {
        ws = new Workspace(memo);
        const file = resolve(f);
        if (file.endsWith(".html")) regenerate(file, logger);
        else if (dirOf(file) && isTs(file)) {
          if (ws.text(file)?.includes("define(")) regenerateDefs(logger);
          recheck(file, logger);
        }
      });
      server.watcher.on("unlink", (f) => {
        ws = new Workspace(memo);
        const file = resolve(f);
        if (file.endsWith(".html")) {
          removeGenerated(file);
          printed.delete(file);
        } else if (dirOf(file) && isDefineFile(file)) regenerateDefs(logger);
        if (dirOf(file)) recheck(file, logger);
      });
    },
    // A template is not a page, so Vite's own reload for a changed .html is ignored by the browser: regenerate it and reload once. A generated module that something else rewrote (ts-dom gen --watch, a checkout) goes through Vite's normal update.
    handleHotUpdate(ctx: { file: string; server: HotServer }) {
      ws = new Workspace(memo);
      const file = resolve(ctx.file);
      const logger = ctx.server.config.logger;
      if (file.endsWith(".html.ts")) {
        const now = read(file);
        if (now !== null && shown.get(file) === now) return [];
        if (now !== null) shown.set(file, now);
        return;
      }
      if (file.endsWith(".html")) {
        if (!dirOf(file)) return;
        if (regenerate(file, logger)) reload(ctx.server, `${file}.ts`);
        return [];
      }
      if (!dirOf(file) || !isTs(file)) return;
      if (ws.text(file)?.includes("define(") || isDefineFile(file)) regenerateDefs(logger);
      recheck(file, logger);
      return;
    },
  };
}
