export interface DoctorOptions {
  dirs: string[];
  /** The module the generated files import (default: @nativele/ts-dom). */
  runtime?: string;
  cwd?: string;
  /** tsconfig path; default: tsconfig.json in cwd */
  project?: string;
}

const readText = (file: string) => (existsSync(file) ? readFileSync(file, "utf8") : null);

/** Whether an include pattern (absolute, forward slashes) makes tsc read the files directly in `dir`. */
function covers(pattern: string, dir: string): boolean {
  const d = dir.split("\\").join("/");
  const star = pattern.indexOf("*");
  if (star === -1) return /\.[cm]?tsx?$/.test(pattern) ? false : d === pattern || d.startsWith(`${pattern}/`);
  const prefix = pattern.slice(0, star).replace(/\/$/, "");
  const rest = pattern.slice(star);
  if (rest.startsWith("**")) return d === prefix || d.startsWith(`${prefix}/`);
  return d === prefix;
}

const TYPECHECK = /(?:^|\s)(?:npx\s+)?(tsc|vue-tsc|svelte-check|ng\s+(?:build|serve|test))(?=\s|$)/;
const TSC_PROJECT = /(?:^|\s)(?:npx\s+)?(?:vue-)?tsc(?:\s.*?)?\s(?:-p|--project)[\s=]+(\S+)/;
const GENERATES = /(?:^|\s)ts-dom\s+(?:gen|check)(?=\s|$)/;
const RUN_SCRIPT = /^(?:npm\s+run(?:-script)?|pnpm(?:\s+run)?|yarn(?:\s+run)?|bun\s+run)\s+([\w:.-]+)/;

/** The commands a script runs in order, with its pre and post scripts and the scripts it runs through npm run (or pnpm, yarn, bun) spelled out. */
function scriptSteps(scripts: Record<string, string>, name: string, depth = 0): string[] {
  const command = scripts[name];
  if (depth > 5 || command === undefined) return [];
  const own = command.split(/&&|;/).flatMap((step) => {
    const ref = RUN_SCRIPT.exec(step.trim())?.[1];
    return ref && scripts[ref] !== undefined ? scriptSteps(scripts, ref, depth + 1) : [step.trim()];
  });
  return [...scriptSteps(scripts, `pre${name}`, depth + 1), ...own, ...scriptSteps(scripts, `post${name}`, depth + 1)];
}

/** The version of the TypeScript the project resolves, or null when it has none. */
function typescriptVersion(cwd: string): string | null {
  try {
    return (JSON.parse(readFileSync(createRequire(join(cwd, "package.json")).resolve("typescript/package.json"), "utf8")) as { version?: string }).version ?? null;
  } catch {
    return null;
  }
}

// TypeScript 5 picks moduleResolution from module, and module from target: ES2015 and later modules (and amd, umd, system, none) resolve the classic way.
const TS5_CLASSIC_MODULES = new Set(["es6", "es2015", "es2020", "es2022", "esnext", "amd", "umd", "system", "none"]);
const implicitlyClassic = (o: Record<string, unknown>): boolean => {
  if (o.module !== undefined) return TS5_CLASSIC_MODULES.has(String(o.module).toLowerCase());
  return !["", "es3", "es5"].includes(String(o.target ?? "").toLowerCase());
};

interface PackageJson {
  scripts?: Record<string, string>;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  prettier?: unknown;
}

const readPackageJson = (file: string): PackageJson => {
  try {
    return JSON.parse(readFileSync(file, "utf8")) as PackageJson;
  } catch {
    return {};
  }
};

const SCRIPT_EXTENSIONS = ["js", "cjs", "mjs", "ts", "cts", "mts"];
const OXFMT_CONFIGS = [".oxfmtrc.json", ".oxfmtrc.jsonc", ...SCRIPT_EXTENSIONS.map((e) => `oxfmt.config.${e}`)];
const PRETTIER_CONFIGS = [".prettierrc", ...["json", "json5", "yaml", "yml", "toml", ...SCRIPT_EXTENSIONS].map((e) => `.prettierrc.${e}`), ...SCRIPT_EXTENSIONS.map((e) => `prettier.config.${e}`)];

const MODULE_SPECIFIERS = /\b(?:from|import)\s*\(?\s*["'](\.{1,2}\/[^"']+)["']|<reference\s+path\s*=\s*["']([^"']+)["']/g;

function importsTagMap(file: string, tagMap: string): boolean {
  const target = tagMap.replace(/\.ts$/, "");
  return [...(readText(file) ?? "").matchAll(MODULE_SPECIFIERS)].some((m) => resolve(dirname(file), (m[1] ?? m[2]) as string).replace(/\.[jt]s$/, "") === target);
}

const templateFolders =(dir: string): string[] => [...new Set(listHtml(dir).map((f) => dirname(f)))];
const hasTemplates = (dir: string): boolean => listHtml(dir).length > 0;

/** Whether a config imports the ts-dom Vite plugin, itself or through the modules it imports by a relative path (a helper that returns tsDom()), up to three imports deep. */
function usesVitePlugin(file: string, text: string, depth = 0, seen = new Set<string>()): boolean {
  if (/@nativele\/ts-dom\/vite|vite-plugin(\.ts)?["']/.test(text)) return true;
  if (depth >= 3) return false;
  seen.add(file);
  for (const m of text.matchAll(/\bfrom\s*["'](\.{1,2}\/[^"']+)["']/g)) {
    const base = resolve(dirname(file), m[1] as string);
    const found = [base, ...[".ts", ".mts", ".js", ".mjs"].map((e) => base.replace(/\.[cm]?js$/, "") + e), ...["ts", "js"].map((e) => join(base, `index.${e}`))].find((f) => !seen.has(f) && existsSync(f) && statSync(f).isFile());
    if (found && usesVitePlugin(found, readText(found) ?? "", depth + 1, seen)) return true;
  }
  return false;
}

/** Check the project set-up an agent or a developer could get wrong; every issue names its rule and ends with a Fix hint. */
export function runDoctor(options: DoctorOptions): LintIssue[] {
  const cwd = options.cwd ?? process.cwd();
  const runtime = options.runtime ?? "@nativele/ts-dom";
  const rel = (f: string) => relative(cwd, f) || ".";
  const split = splitDirs(options.dirs, cwd);
  const issues: LintIssue[] = [...split.missing];
  const add = (rule: keyof typeof DOCTOR_RULES, severity: LintIssue["severity"], message: string, at: { file?: string; line?: number } = {}) => issues.push({ file: at.file ?? ".", line: at.line ?? 1, col: 1, rule, severity, message });
  const dirs = split.dirs.map((d) => resolve(cwd, d));

  const configs = projectConfigs(cwd, options.project);
  let paths: Record<string, unknown> = {};
  if (!configs.length) {
    if (options.project) add("no-tsconfig", "error", `The tsconfig ${options.project} given with --project does not exist. Fix: pass the path of the tsconfig the project type-checks with.`);
    else add("no-tsconfig", "error", 'There is no tsconfig.json. Fix: add one with "strict": true, "lib": ["ES2022", "DOM"] and "moduleResolution": "bundler" (or "NodeNext").');
  }
  const tsVersion = typescriptVersion(cwd);
  const tsMajor = tsVersion === null ? null : Number.parseInt(tsVersion, 10);
  const includes: string[] = [];
  let everyConfigIncludes = true;
  const scanned = dirs.map((dir) => ({ dir, folders: templateFolders(dir) }));
  const targets = scanned.flatMap(({ dir, folders }) => (folders.length ? folders : [dir]));
  const read = configs.map((path) => ({ path, config: readTsConfig(path) }));
  const covering = read.filter(({ config: { include } }) => !include || targets.some((t) => include.some((p) => covers(p, t))));
  for (const { path: configPath, config } of read) {
    const o = config.compilerOptions;
    const file = rel(configPath);
    paths = { ...paths, ...(o.paths as Record<string, unknown> | undefined) };
    if (config.include) includes.push(...config.include);
    else everyConfigIncludes = false;
    if (covering.length && !covering.some((r) => r.path === configPath)) continue;
    const lost = "so tsc does not report values that may be null (a querySelector result or an optional ref used without a check) or parameters and variables that are implicitly any (a handler parameter without a type); the names in the templates are checked either way";
    if (o.strict === false) add("tsconfig-not-strict", "warning", `compilerOptions.strict is false, ${lost}. Fix: set "strict": true.`, { file });
    else if (o.strict === undefined && tsMajor === null) add("tsconfig-not-strict", "warning", `compilerOptions.strict is not set, and the TypeScript version could not be determined (typescript is not resolvable from this project): TypeScript 5 leaves strict off by default (6 and later turn it on), ${lost}. Fix: set "strict": true.`, { file });
    else if (o.strict === undefined && tsMajor !== null && tsMajor < 6) add("tsconfig-not-strict", "warning", `compilerOptions.strict is not set, and TypeScript ${tsVersion} leaves it off by default (6 and later turn it on), ${lost}. Fix: set "strict": true.`, { file });
    const lib = o.lib as string[] | undefined;
    if (lib && !lib.some((l) => l.toLowerCase() === "dom")) add("tsconfig-no-dom-lib", "error", 'compilerOptions.lib leaves out DOM, so element types such as HTMLButtonElement are missing. Fix: add "DOM" to lib.', { file });
    const cannotResolve = `which cannot resolve the package "${runtime}" that every generated file imports (TS2792 Cannot find module), so no component gets its types`;
    if (String(o.moduleResolution ?? "").toLowerCase() === "classic") {
      const why =
        tsMajor === null ? `${cannotResolve}; TypeScript 6 deprecates it (TS5107) and 7 removes it (TS5108)`
        : tsMajor >= 7 ? `which TypeScript ${tsVersion} no longer supports, so tsc stops with TS5108 before checking anything`
        : tsMajor === 6 ? `which TypeScript ${tsVersion} deprecates, so tsc stops with TS5107 before checking anything`
        : cannotResolve;
      add("tsconfig-classic-resolution", "error", `moduleResolution is "classic", ${why}. Fix: use "bundler" (or "NodeNext" with "module": "NodeNext").`, { file });
    } else if (o.moduleResolution === undefined && tsMajor !== null && tsMajor < 6 && implicitlyClassic(o)) {
      const by = o.module !== undefined ? `"module": ${JSON.stringify(o.module)}` : `"target": ${JSON.stringify(o.target)} (which makes module ES2015 or later)`;
      add("tsconfig-classic-resolution", "error", `${by} without "moduleResolution" makes TypeScript ${tsVersion} resolve modules the classic way, ${cannotResolve}. Fix: add "moduleResolution": "bundler" (or set "module" and "moduleResolution" to "NodeNext").`, { file });
    }
  }
  if (configs.length && everyConfigIncludes) {
    const missed = new Set<string>();
    for (const folder of scanned.flatMap((s) => s.folders)) if (!includes.some((p) => covers(p, folder))) missed.add(rel(folder));
    for (const folder of missed) {
      add("tsconfig-misses-templates", "error", `No tsconfig include covers ${folder}, which has templates, so their generated types are never checked. Fix: add "${folder === "." ? "**/*" : `${folder}/**/*`}" to include.`, { file: rel(configs[0] as string) });
    }
  }
  // Unlike the x.html.ts files, which their components import, ts-dom-tags.ts usually reaches the program only through include; a package entry may import or re-export it.
  for (const { dir, folders } of scanned) {
    const tags = scanTags(dir).map((t) => `<${t.tag}>`);
    if (!tags.length) continue;
    const tagMap = join(dir, "ts-dom-tags.ts");
    const owners = read.filter(({ config: { include } }) => !include || (folders.length ? folders : [dir]).some((t) => include.some((p) => covers(p, t))));
    const left = owners.map(({ path, config }) => ({ path, config, why: leftOutBy(config, dirname(path), tagMap) }));
    const first = left[0];
    if (!first?.why || left.some((l) => !l.why)) continue;
    const configDir = dirname(first.path);
    const program = [...listTs(dir), ...(first.config.files ?? []), ...listTs(configDir).filter((f) => !leftOutBy(first.config, configDir, f))];
    if (program.some((f) => importsTagMap(f, tagMap))) continue;
    const own = (p: string) => relative(configDir, p).split("\\").join("/") || ".";
    const effect = `so tsc types the tags defined in ${rel(dir)} (${tags.slice(0, 3).join(", ")}${tags.length > 3 ? ", ..." : ""}) as plain HTMLElement in document.createElement, querySelector and refs, and every list of item components fails with item-not-in-tag-map`;
    add(
      "tsconfig-misses-tag-map",
      "error",
      first.why.by === "include"
        ? `The include of ${rel(first.path)} does not match ${rel(tagMap)}, and no file imports it, ${effect}. Fix: add "${own(tagMap)}" to include.`
        : `The exclude pattern "${own(first.why.pattern)}" in ${rel(first.path)} removes ${rel(tagMap)} from the program, and no file imports it, ${effect}. Fix: narrow the pattern so it leaves ts-dom-tags.ts in, or add "${own(tagMap)}" to files (files are kept even when exclude matches them).`,
      { file: rel(first.path) },
    );
  }

  let resolvable = Object.keys(paths).includes(runtime);
  if (!resolvable) {
    try {
      createRequire(join(cwd, "package.json")).resolve(`${runtime}/package.json`);
      resolvable = true;
    } catch {
      resolvable = false;
    }
  }
  if (!resolvable) add("runtime-not-installed", "error", `The generated files import "${runtime}", which cannot be resolved from this project. Fix: npm i ${runtime}.`);

  for (const d of dirs) {
    for (const f of listTs(d)) {
      const lines = readFileSync(f, "utf8").split("\n");
      lines.forEach((text, i) => {
        const m = templateImports(text).find((t) => !t.js);
        if (m) add("template-import-without-js", "error", `${m.html} is imported without .js, which works only through a bundler plugin that Nativele does not provide, and lint does not treat it as a Nativele template. Fix: import "${m.html}.js" (TypeScript maps it to the generated ${m.html}.ts); if it belongs to another template system, scan only the Nativele folders.`, { file: rel(f), line: i + 1 });
      });
    }
  }

  const scannedHtml = new Set(dirs.flatMap((d) => listHtml(d)));
  if (scannedHtml.size) {
    for (const f of listTs(cwd)) {
      for (const m of readFileSync(f, "utf8").matchAll(/templateUrl\s*:\s*["'`]([^"'`]+\.html)["'`]/g)) {
        const html = resolve(dirname(f), m[1] as string);
        if (!scannedHtml.has(html)) continue;
        scannedHtml.delete(html);
        add("framework-template", "error", `${rel(html)} is the Angular template of ${rel(f)} (templateUrl), not a Nativele template, so ts-dom gen reports its Angular syntax as errors. Fix: scan only the folder with the Nativele templates (for example ts-dom gen src/nv, and the same folder for check, doctor and tsDom({ dirs })).`, { file: rel(html) });
      }
    }
  }

  const viteConfig = ["vite.config.ts", "vite.config.mts", "vite.config.js", "vite.config.mjs"].map((n) => join(cwd, n)).find((f) => existsSync(f));
  const vite = viteConfig ? (readText(viteConfig) as string) : null;
  if (viteConfig && vite !== null && !usesVitePlugin(viteConfig, vite)) {
    add("vite-plugin-missing", "warning", 'The Vite config does not use the ts-dom plugin, so templates are not regenerated while the dev server runs. Fix: import { tsDom } from "@nativele/ts-dom/vite" and add tsDom() to plugins.', { file: rel(viteConfig) });
  }
  const vitestConfig = ["ts", "mts", "cts", "js", "mjs", "cjs"].map((ext) => join(cwd, `vitest.config.${ext}`)).find((f) => existsSync(f));
  const vitest = vitestConfig ? (readText(vitestConfig) as string) : null;
  if (vitestConfig && vitest !== null && !usesVitePlugin(vitestConfig, vitest) && !/["']\.\/vite\.config(\.[cm]?[jt]s)?["']/.test(vitest)) {
    add("vite-plugin-missing", "warning", `${rel(vitestConfig)} replaces the Vite config for Vitest and does not use the ts-dom plugin, so the templates are not generated when the tests start and a clean checkout fails to resolve ./x.html.js. Fix: add tsDom() to its plugins, or merge the Vite config into it: mergeConfig(viteConfig, defineConfig({ test: { ... } })) with viteConfig imported from "./vite.config".`, { file: rel(vitestConfig) });
  }

  const ws = new Workspace();
  const workspace = upToWorkspaceRoot(ws, cwd);
  const nearest = (names: readonly string[]) => workspace.flatMap((d) => names.map((n) => join(d, n))).find((f) => existsSync(f));
  const oxlintrc = nearest([".oxlintrc.json", ".oxlintrc.jsonc", "oxlintrc.json", "oxlint.config.ts", "oxlint.config.mts"]);
  const lintConfigs = [oxlintrc ? readText(oxlintrc) : null, vite && /\blint\s*:/.test(vite) ? vite : null].filter((t): t is string => t !== null);
  if (lintConfigs.length && !lintConfigs.some((t) => /@nativele\/ts-dom\/oxlint|oxlint-plugin(\.ts)?["']/.test(t))) {
    add("oxlint-plugin-missing", "warning", 'The lint config does not load the ts-dom oxlint plugin, so unused markup, data flow and accessibility rules do not run in the editor. Fix: add { name: "ts-dom", specifier: "@nativele/ts-dom/oxlint" } to jsPlugins and enable "ts-dom/unused-markup".', { file: rel(oxlintrc ?? (viteConfig as string)) });
  }

  const pkgText = readText(join(cwd, "package.json"));
  const pkg = pkgText ? (JSON.parse(pkgText) as PackageJson) : {};

  const ignoresGenerated = workspace.some((d) => (readText(join(d, ".gitignore")) ?? "").split("\n").some((l) => !l.trim().startsWith("!") && /\*\.html\.ts\s*$/.test(l)));
  if (ignoresGenerated && dirs.some(hasTemplates)) {
    const all = pkg.scripts ?? {};
    const checksTemplates = (step: string) => {
      const project = TSC_PROJECT.exec(step)?.[1];
      if (!project && !/(?:^|\s)(?:npx\s+)?(?:vue-)?tsc(?=\s|$)/.test(step)) return true;
      const config = resolve(cwd, project ?? "tsconfig.json");
      const configs = projectConfigs(cwd, existsSync(config) && statSync(config).isDirectory() ? join(config, "tsconfig.json") : config);
      return !configs.length || configs.some((c) => {
        const include = readTsConfig(c).include;
        return !include || targets.some((t) => include.some((p) => covers(p, t)));
      });
    };
    const dirArgs = options.dirs.join(" ");
    for (const name of Object.keys(all)) {
      if (/^(pre|post)./.test(name) && all[name.replace(/^(pre|post)/, "")] !== undefined) continue;
      const step = scriptSteps(all, name).find((s) => GENERATES.test(s) || (TYPECHECK.test(s) && checksTemplates(s)));
      if (step === undefined || GENERATES.test(step)) continue;
      const tool = (TYPECHECK.exec(step) as RegExpExecArray)[1]?.replace(/\s+/g, " ");
      const line = (pkgText as string).split("\n").findIndex((l) => l.includes(`${JSON.stringify(name)}:`)) + 1;
      add("typecheck-before-gen", "warning", `The script "${name}" runs ${tool} before any ts-dom gen, and .gitignore leaves out *.html.ts, so on a clean checkout ${tool} fails with TS2307 (cannot find module './x.html.js'). Fix: put "ts-dom gen ${dirArgs} && " in front of it, or use "ts-dom check ${dirArgs}" as the type check when the project uses plain tsc.`, { file: "package.json", ...(line ? { line } : {}) });
    }
  }
  const prettierIgnore = nearest([".prettierignore"]);
  const ignoredHtml = /(^|\n)\s*(\*\*\/)?\*\.html\s*($|\n)/.test(prettierIgnore ? (readText(prettierIgnore) ?? "") : "");
  const formatterIn = (d: string): string | undefined => {
    const file = join(d, "package.json");
    const json = readPackageJson(file);
    const ds = { ...json.dependencies, ...json.devDependencies };
    const runs = (tool: RegExp) => Object.values(json.scripts ?? {}).some((c) => tool.test(c));
    const oxfmt = OXFMT_CONFIGS.map((n) => join(d, n)).find((f) => existsSync(f)) ?? ("oxfmt" in ds || runs(/(^|[\s;&|])(oxfmt|vp fmt)(\s|$)/) ? file : undefined);
    if (oxfmt || ignoredHtml) return oxfmt;
    return PRETTIER_CONFIGS.map((n) => join(d, n)).find((f) => existsSync(f)) ?? ("prettier" in json || "prettier" in ds || runs(/(^|[\s;&|])prettier(\s|$)/) ? file : undefined);
  };
  const formatter = workspace.map(formatterIn).find((f) => f !== undefined) ?? (vite !== null && /\bfmt\s*:/.test(vite) ? viteConfig : undefined);
  const collapseScript = Object.entries(pkg.scripts ?? {}).find(([, c]) => c.includes("--whitespace=collapse"))?.[0];
  const collapseVite = vite !== null && /whitespace\s*:\s*["']collapse["']/.test(vite);
  const generatedModes = dirs.flatMap((d) => listHtml(d)).flatMap((f) => {
    const head = (readText(`${f}.ts`) ?? "").split("\n", 3);
    return head[0]?.startsWith("// Generated by ts-dom.") ? [{ file: `${f}.ts`, collapse: head.includes("// whitespace: collapse") }] : [];
  });
  const preserved = generatedModes.filter((g) => !g.collapse);
  if ((collapseScript || collapseVite) && preserved.length) {
    const asker = collapseScript ? `The script "${collapseScript}"` : "The Vite config";
    const rerun = collapseScript ? `npm run ${collapseScript}` : `ts-dom gen ${options.dirs.join(" ")} --whitespace=collapse`;
    add("formatter-whitespace", "warning", `${asker} asks for whitespace "collapse", but ${preserved.length === 1 ? "this generated file was" : `${preserved.length} generated files (this one first) were`} written with "preserve" (by a gen or check run without the flag, for example), and a run without --whitespace keeps the mode a file was last written with, so the page gets the whitespace as written instead of collapsed. Fix: regenerate with the flag once: ${rerun}.`, { file: rel((preserved[0] as { file: string }).file) });
  }
  const collapsed = collapseScript !== undefined || collapseVite || generatedModes.some((g) => g.collapse);
  if (formatter && !collapsed && dirs.some(hasTemplates)) {
    add("formatter-whitespace", "warning", 'A formatter (oxfmt or Prettier) is set up, and templates keep their whitespace as written, so reformatting a template can change the spacing on the page. Fix: generate with whitespace "collapse" (ts-dom gen --whitespace=collapse, or tsDom({ whitespace: "collapse" })).', { file: rel(formatter) });
  }

  const packages = new Set([cwd, ...dirs].map((d) => packageOf(ws, resolve(d))));
  const reported = new Set<string>();
  for (const pkgDir of packages) {
    for (const m of pkgDir ? manifestsAt(ws, pkgDir) : []) {
      if (!("error" in m) || reported.has(m.file)) continue;
      reported.add(m.file);
      add("custom-elements-manifest", "warning", `The custom elements manifest that ${m.pkg} declares in the customElements field of its package.json, ${rel(m.file)}, ${m.error}, so lint does not check the attributes, events and slots of its elements, and lists them in unchecked-custom-elements instead. Fix: update ${m.pkg}, or report the broken manifest to its maintainers.`, { file: rel(m.file) });
    }
  }

  for (const skill of listSkills()) {
    const copies = workspace.flatMap((d) => installedCopies(d, skill.name));
    const shipped = readFileSync(join(skill.dir, "SKILL.md"), "utf8");
    for (const copy of copies) {
      if (readFileSync(join(copy, "SKILL.md"), "utf8") !== shipped) {
        add("skill-outdated", "warning", `${rel(copy)} differs from the ${skill.name} Skill shipped with the installed Nativele. Fix: run ts-dom skills add ${skill.name} to replace it with the shipped version.`, { file: rel(join(copy, "SKILL.md")) });
      }
    }
  }
  return issues;
}
